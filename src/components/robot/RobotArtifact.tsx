"use client";

import React, { useState } from "react";
import { WorkforceArtifact } from "@/services/agentic/types/agentic.types";
import { Download, FileText, Check, Copy, ExternalLink, Code } from "lucide-react";

interface RobotArtifactProps {
  artifacts?: WorkforceArtifact[];
  className?: string;
  onSelectArtifact?: (artifact: WorkforceArtifact) => void;
}

export function RobotArtifact({
  artifacts = [],
  className = "",
  onSelectArtifact,
}: RobotArtifactProps) {
  const [copiedId, setCopiedId] = useState<string | null>(null);

  if (!artifacts || artifacts.length === 0) {
    return (
      <div className={`p-4 rounded-xl bg-slate-900/60 border border-slate-800 text-xs text-slate-500 italic ${className}`}>
        No artifacts generated yet. Work products will be registered upon verification.
      </div>
    );
  }

  const handleExportMarkdown = (artifact: WorkforceArtifact, e: React.MouseEvent) => {
    e.stopPropagation();
    const mdContent = `# ${artifact.title}
**Artifact ID:** ${artifact.artifactId}  
**Type:** ${artifact.artifactType}  
**Status:** ${artifact.status}  
**Version:** v${artifact.version}  
**Created By:** ${(artifact.sourceWorker || "WORKER").replace("-worker", "").toUpperCase()}  
**Created At:** ${new Date(artifact.createdAt).toISOString()}  

---

## Executive Summary & Description
${artifact.description || "No description provided."}

---

## Technical & Verification Evidence
\`\`\`json
${JSON.stringify(artifact.structuredData || artifact.evidence || {}, null, 2)}
\`\`\`

---
*Generated by ELMO AI Workforce Operating System • Verified Work Product*
`;

    const blob = new Blob([mdContent], { type: "text/markdown;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", `${artifact.artifactId || "artifact"}_v${artifact.version}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleExportJson = (artifact: WorkforceArtifact, e: React.MouseEvent) => {
    e.stopPropagation();
    const jsonString = JSON.stringify(artifact, null, 2);
    const blob = new Blob([jsonString], { type: "application/json;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", `${artifact.artifactId || "artifact"}_v${artifact.version}.json`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleCopyEvidence = (artifact: WorkforceArtifact, e: React.MouseEvent) => {
    e.stopPropagation();
    const content = JSON.stringify(artifact.structuredData || artifact.evidence || artifact.description || {}, null, 2);
    navigator.clipboard.writeText(content).then(() => {
      setCopiedId(artifact.artifactId);
      setTimeout(() => setCopiedId(null), 2000);
    });
  };

  const getStatusBadge = (status: WorkforceArtifact["status"]) => {
    switch (status) {
      case "VERIFIED":
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold bg-emerald-500/10 border border-emerald-500/30 text-emerald-400">
            ✓ Verified
          </span>
        );
      case "DRAFT":
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold bg-cyan-500/10 border border-cyan-500/30 text-cyan-400">
            ● Draft
          </span>
        );
      case "SUBMITTED":
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold bg-amber-500/10 border border-amber-500/30 text-amber-400">
            ⏸ Awaiting Approval
          </span>
        );
      case "REJECTED":
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold bg-rose-500/10 border border-rose-500/30 text-rose-400">
            ✗ Rejected
          </span>
        );
      case "SUPERSEDED":
      default:
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold bg-slate-800 text-slate-400">
            Superseded
          </span>
        );
    }
  };

  const getTypeIcon = (type: string) => {
    switch (type) {
      case "RESEARCH_REPORT":
        return "🔍";
      case "ANALYTICS_REPORT":
        return "📊";
      case "STRATEGY_DOC":
        return "🎯";
      case "COPY_SUITE":
        return "✍️";
      case "LANDING_PAGE_CODE":
        return "💻";
      case "AUTOMATION_CONFIG":
        return "⚡";
      case "AUDIT_REPORT":
        return "🛡️";
      default:
        return "📦";
    }
  };

  return (
    <div className={`space-y-3 ${className}`}>
      {artifacts.map((a) => (
        <div
          key={a.artifactId}
          onClick={() => onSelectArtifact?.(a)}
          className={`p-3.5 rounded-xl bg-slate-900/90 border border-slate-800 transition-all ${
            onSelectArtifact ? "hover:border-emerald-500/40 hover:bg-slate-900 cursor-pointer" : ""
          }`}
        >
          <div className="flex items-center justify-between gap-2">
            <div className="flex items-center gap-2.5 min-w-0">
              <span className="text-lg flex-shrink-0">{getTypeIcon(a.artifactType)}</span>
              <div className="min-w-0">
                <h4 className="text-xs font-bold text-slate-200 truncate">
                  {a.title}
                </h4>
                <span className="text-[10px] text-slate-400">
                  {String(a.artifactType).replace(/_/g, " ")} • v{a.version}
                </span>
              </div>
            </div>
            {getStatusBadge(a.status)}
          </div>

          {a.description && (
            <p className="text-[11px] text-slate-400 mt-2.5 line-clamp-2 leading-relaxed bg-slate-950/60 p-2.5 rounded-lg border border-slate-800/80">
              {a.description}
            </p>
          )}

          <div className="flex flex-wrap items-center justify-between gap-2 text-[10px] text-slate-500 mt-3 pt-2 border-t border-slate-800/60">
            <div className="flex items-center gap-3">
              <span>By: <strong>{(a.sourceWorker || "WORKER").replace("-worker", "").toUpperCase()}</strong></span>
              <span>{new Date(a.createdAt).toLocaleDateString()}</span>
            </div>

            {/* Export & Action Buttons */}
            <div className="flex items-center gap-1.5" onClick={(e) => e.stopPropagation()}>
              <button
                type="button"
                onClick={(e) => handleCopyEvidence(a, e)}
                className="px-2 py-1 rounded bg-slate-800/80 hover:bg-slate-700 text-slate-300 transition-colors flex items-center gap-1"
                title="Copy evidence payload"
              >
                {copiedId === a.artifactId ? (
                  <>
                    <Check className="w-3 h-3 text-emerald-400" />
                    <span className="text-emerald-400">Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3 h-3" />
                    <span>Copy</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={(e) => handleExportMarkdown(a, e)}
                className="px-2 py-1 rounded bg-emerald-950/40 hover:bg-emerald-900/50 text-emerald-300 border border-emerald-500/30 transition-colors flex items-center gap-1"
                title="Download as Markdown"
              >
                <Download className="w-3 h-3" />
                <span>MD</span>
              </button>

              <button
                type="button"
                onClick={(e) => handleExportJson(a, e)}
                className="px-2 py-1 rounded bg-cyan-950/40 hover:bg-cyan-900/50 text-cyan-300 border border-cyan-500/30 transition-colors flex items-center gap-1"
                title="Download as JSON"
              >
                <Code className="w-3 h-3" />
                <span>JSON</span>
              </button>
            </div>
          </div>
        </div>
      ))}
    </div>
  );
}
