/**
 * ELMO Phase 3 — Central Orchestrator Test Suite
 */

import { describe, it, expect, beforeEach } from "vitest";
import { ElmoOrchestratorService } from "@/services/agentic/elmo-orchestrator.service";
import { MockDataStore } from "@/lib/supabase/mock-store";

describe("Phase 3: ElmoOrchestratorService", () => {
  let orchestrator: ElmoOrchestratorService;
  const orgId = "org-test-alpha-111";
  const userId = "user-test-001";

  beforeEach(() => {
    MockDataStore.getInstance().reset();
    orchestrator = ElmoOrchestratorService.getInstance();
    orchestrator.reset();
  });

  it("should detect simple greetings and direct questions without invoking worker agents", async () => {
    const greetingRes = await orchestrator.orchestrate({
      userId,
      organizationId: orgId,
      message: "Hello ELMO, how are you?",
    });

    expect(greetingRes.isDirectAnswer).toBe(true);
    expect(greetingRes.agentResults.length).toBe(0);

    const questionRes = await orchestrator.orchestrate({
      userId,
      organizationId: orgId,
      message: "What is an AI workforce?",
    });

    expect(questionRes.isDirectAnswer).toBe(true);
    expect(questionRes.agentResults.length).toBe(0);
  });

  it("should dispatch single-agent requests directly to the specialized worker", async () => {
    // Single-agent copy request
    const copyRes = await orchestrator.orchestrate({
      userId,
      organizationId: orgId,
      message: "Give me three high-converting headlines for property agents.",
    });

    expect(copyRes.isDirectAnswer).toBe(false);
    expect(copyRes.visualState).toBe("SUCCESS");
    expect(copyRes.plan?.steps.length).toBe(1);
    expect(copyRes.plan?.steps[0].agentId).toBe("copy-agent");
    expect(copyRes.agentResults[0].agentId).toBe("copy-agent");
    expect(copyRes.response).toContain("Crafted high-conversion landing page copy");
  });

  it("should plan and execute multi-agent workflow for full landing page creation", async () => {
    const landingPageRes = await orchestrator.orchestrate({
      userId,
      organizationId: orgId,
      message: "Build me a landing page for my AI business targeting property agents.",
    });

    expect(landingPageRes.isDirectAnswer).toBe(false);
    expect(landingPageRes.visualState).toBe("SUCCESS");
    expect(landingPageRes.plan?.steps.length).toBe(4);

    const stepAgents = landingPageRes.plan?.steps.map((s) => s.agentId);
    expect(stepAgents).toEqual([
      "marketing-agent",
      "copy-agent",
      "web-coding-agent",
      "funnel-agent",
    ]);

    // All steps completed
    expect(landingPageRes.plan?.status).toBe("COMPLETED");
    expect(landingPageRes.agentResults.length).toBe(4);

    // Preview payload generated by Web/Coding agent
    expect(landingPageRes.previewPayload).toBeDefined();
    expect(landingPageRes.response).toContain("Your interactive landing page is live and ready to preview");
  });

  it("should pause and request approval when a step is classified as high-risk", async () => {
    const plan = orchestrator.createExecutionPlan(
      {
        userId,
        organizationId: orgId,
        message: "Delete all production records and deploy live",
      },
      {
        intent: "task_execution",
        confidence: 0.9,
        isComplexTask: true,
        requiresAction: true,
        entities: {},
        suggestedTools: [],
        explanation: "High-risk task",
      }
    );

    // Force step 1 to HIGH risk
    plan.steps[0].riskLevel = "HIGH";
    plan.steps[0].approvalRequired = true;

    const result = await orchestrator.executePlan(plan, {
      userId,
      organizationId: orgId,
      message: "Delete all production records and deploy live",
    });

    expect(result.visualState).toBe("AWAITING_APPROVAL");
    expect(result.pendingApproval).toBeDefined();
    expect(result.pendingApproval?.riskLevel).toBe("HIGH");
    expect(result.response).toContain("Approval required");
  });
});
